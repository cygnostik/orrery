test('selection signal has a finite intermediate stroke and settles on reduced-motion interruption',async({page})=>{
 await page.setViewportSize({width:1440,height:1400});await ready(page);
 // Navigation can scroll the signal offscreen, correctly settling it. Keep
 // this signal-timing test visible; separate UI tests cover pointer selection.
 await page.evaluate(()=>scrollTo(0,0));
 await page.getByRole('button',{name:'04 Mars',exact:true}).evaluate(el=>el.click());
 const path=page.locator('#selection-signal');
 await expect(path).toHaveAttribute('data-motion-state','running');
 const offset=await path.evaluate(el=>{const a=el.getAnimations()[0];a.pause();a.currentTime=450;return parseFloat(getComputedStyle(el).strokeDashoffset);});
 expect(offset).toBeGreaterThan(0);expect(offset).toBeLessThan(1);
 await page.emulateMedia({reducedMotion:'reduce'});
 await expect(path).toHaveAttribute('data-motion-state','settled');
 expect(await path.evaluate(el=>el.getAnimations().length)).toBe(0);
 await page.getByRole('button',{name:'05 Jupiter',exact:true}).evaluate(el=>el.click());
 await expect(page.locator('#body-name')).toHaveText('Jupiter');
 await expect(path).toHaveAttribute('data-motion-state','settled');
 await expect(path).toHaveAttribute('stroke-dashoffset','0');
});
