const ready=async page=>{await page.goto('/');await expect.poll(()=>page.evaluate(()=>window.__orrery?.diagnostics().ready),{timeout:15000}).toBe(true);};
test('the actual 3D crank reverses time without orbiting the camera, and its switch shares playback',async({page})=>{
 await ready(page);await page.locator('#simulation-date').fill('2026-09-05');await page.evaluate(()=>scrollTo(0,0));await page.waitForTimeout(400);
 const canvas=page.locator('#universe canvas'),rect=await canvas.boundingBox();
 const before=await page.evaluate(()=>({state:window.__orrery.getState(),diag:window.__orrery.diagnostics()}));
 const points=before.diag.controlPoints,grip=points.crankGrip,axle=points.crankAxle;
 expect(grip.visible).toBe(true);const dx=grip.x-axle.x,dy=grip.y-axle.y;
 await page.mouse.move(rect.x+grip.x,rect.y+grip.y);await page.mouse.down();
 expect(await page.evaluate(()=>window.__orrery.diagnostics().draggingCrank)).toBe(true);
 await page.mouse.move(rect.x+axle.x-dy,rect.y+axle.y+dx);
 await expect.poll(()=>page.evaluate(()=>window.__orrery.getState().date)).not.toBe(before.state.date);
 await page.mouse.move(rect.x+grip.x,rect.y+grip.y);await page.mouse.up();await page.waitForTimeout(350);
 const after=await page.evaluate(()=>({state:window.__orrery.getState(),diag:window.__orrery.diagnostics()}));
 expect(Math.abs(Date.parse(after.state.date)-Date.parse(before.state.date))).toBeLessThanOrEqual(2);
 expect(after.state.playing).toBe(false);expect(after.diag.draggingCrank).toBe(false);expect(after.diag.camera).toEqual(before.diag.camera);
 const sw=after.diag.controlPoints.autoSwitch;expect(sw.visible).toBe(true);
 await page.mouse.click(rect.x+sw.x,rect.y+sw.y);await expect(page.getByRole('switch',{name:'Automatic movement',exact:true})).toHaveAttribute('aria-checked','true');
 await expect(page.locator('#auto-drive')).toHaveAttribute('aria-checked','true');
 await page.mouse.click(rect.x+sw.x,rect.y+sw.y);await expect(page.locator('#auto-drive')).toHaveAttribute('aria-checked','false');
});
